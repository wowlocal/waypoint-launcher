#!/bin/zsh
# Builds a signed, notarized and stapled Waypoint DMG plus the Sparkle appcast
# that installed copies update from, and publishes them like snippets does:
# the DMG and appcast go to S3 (Yandex Object Storage), which is the live
# update feed, and the DMG is mirrored as a GitHub release.
#
#   scripts/release.sh 0.2.0             # → dist/Waypoint-0.2.0.dmg (+ .sha256, appcast.xml)
#   scripts/release.sh 0.2.0 --publish   # …tag v0.2.0, upload to S3, create the GitHub release
#   scripts/release.sh tip --publish     # a tip build of this branch, on the tip feed
#   scripts/release.sh 0.2.0 --tip-feed  # after a release: (again) add it to the tip feed
#   scripts/release.sh 0.2.0 --homebrew  # after a release: (again) point the Homebrew cask at it
#
# Tip builds (like Ghostty's) are for trying what's next: experimental work
# that may live on a branch. A tip is built from the checked-out branch,
# which must contain the latest origin/main: tips are main plus more, never
# behind it. It is versioned after the latest release (1.1.4-tip.3), has
# its own feed (waypoint/tip/appcast.xml), which only tip builds follow, and
# replaces the GitHub pre-release tagged "tip". Stable users never see one.
# Tip build numbers sit between releases: after release 181 come 181.1,
# 181.2…, newer than it and older than the next release (182 or more). So
# Sparkle takes a copy from the release to a tip, from tip to tip, and on to
# the next release; going back to the current release, which Sparkle refuses
# (a lower number), Waypoint does itself (ReleaseReturn.swift). The tip feed
# also carries the newest release (scripts/merge-tip-appcast.py), so tip
# copies move on to a release as soon as it's out; publishing a release
# updates it too. Tips are turned on and off in Settings ▸ General.
# Tips reuse the published Windows runtime. The "tip" tag moves: a clone
# that fetched it before needs `git fetch --tags --force` (or `git tag -d tip`).
#
# --publish needs S3 credentials in AWS_ACCESS_KEY_ID / AWS_SECRET_ACCESS_KEY,
# or in scripts/release.env (gitignored, same format as snippets' Distribution/.env).
#
#   SIGN_IDENTITY   Developer ID Application identity (default: first one in the keychain)
#   NOTARY_KEYCHAIN_PROFILE  notarytool keychain profile (default: keys-cli-notary).
#                   NOTARY_PROFILE remains a compatibility override.
#   NOTARY_KEY, NOTARY_KEY_ID, NOTARY_ISSUER
#                   or notarize with an App Store Connect API key (.p8 path, key ID, and
#                   the issuer ID for a team key; an individual key has none)
#   NOTES_FILE      release notes for --publish (default: generated by GitHub)
#   REUSE_WINDOWS_ASSETS_FROM  an existing release tag whose unchanged Windows
#                   assets to reuse, without downloading, rechecking or mirroring
#                   the large archives again. Link that release in NOTES_FILE.
#   Sparkle signing key: the private EdDSA key in the keychain under account "waypoint"
#                   (generate_keys --account waypoint); its public half is in scripts/bundle.sh.
#   ALLOW_DIRTY=1   build from a working tree with uncommitted changes
set -euo pipefail
cd "${0:A:h}/.."

step() { print -P "%F{cyan}==>%f $*" }
fail() { print -P "%F{red}error:%f $*" >&2; exit 1 }

[[ "${WINDOWS_EXPERIMENTAL:-0}" != "1" ]] || fail "experimental Windows profiles cannot use the public release pipeline"

version="${1:-}"
publish=0
mode="${2:-}"
[[ "$mode" == "--publish" || "$mode" == "--publish-only" ]] && publish=1
tip_feed_only=0
[[ "$mode" == "--tip-feed" ]] && tip_feed_only=1
homebrew_only=0
[[ "$mode" == "--homebrew" ]] && homebrew_only=1
channel=stable
[[ "$version" == "tip" ]] && channel=tip
[[ ( "$channel" == "tip" || "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ) && ( -z "$mode" || "$mode" == "--publish" || "$mode" == "--publish-only" ) ]] \
    || [[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ && ( "$mode" == "--tip-feed" || "$mode" == "--homebrew" ) ]] \
    || fail "usage: scripts/release.sh <x.y.z|tip> [--publish|--publish-only] | <x.y.z> --tip-feed|--homebrew"

tag="v$version"
repo_url="https://github.com/wowlocal/waypoint-launcher"
# Where updates are served from. Fixed on purpose, not configurable: installed
# copies have this feed baked in (scripts/bundle.sh), and the bucket is shared
# with other apps, so a stray S3_PREFIX must never redirect an upload.
s3_endpoint="https://storage.yandexcloud.net"
s3_region="ru-central1"
s3_bucket="macos-releases"
s3_prefix="waypoint"
public_base="$s3_endpoint/$s3_bucket/$s3_prefix"
feed_url="$public_base/appcast.xml"
# Where this channel's DMGs and feed go: the prefix itself, or tip/ in it.
channel_prefix="$s3_prefix"
build_number=""
s3() { aws s3 "$@" --endpoint-url "$s3_endpoint" --region "$s3_region" }

# The build number in the live tip feed; empty only when there is no tip yet.
# Any other failure stops the run: guessing low would strand tip users.
live_tip_build() {
    local body code build
    body="$(mktemp)"
    code="$(curl -sS --max-time 30 -o "$body" -w '%{http_code}' "$feed_url")" || { rm -f "$body"; fail "can't read $feed_url" }
    case "$code" in
        403|404) rm -f "$body"; return 0 ;;
        200) ;;
        *) rm -f "$body"; fail "$feed_url answered HTTP $code" ;;
    esac
    build="$(sed -n 's/.*sparkle:version="\([0-9.]*\)".*/\1/p;s/.*<sparkle:version>\([0-9.]*\)<.*/\1/p' "$body" | sort -t. -k1,1n -k2,2n | tail -1)"
    rm -f "$body"
    [[ -n "$build" ]] || fail "can't find the build number in $feed_url"
    print -r -- "$build"
}

# The newest release whose assets include the Windows runtime in
# build/windows-runtime-release (stable releases that reuse it don't attach it).
newest_release_with_windows_runtime() {
    python3 - "${WINDOWS_COMPONENT_RELEASE:-build/windows-runtime-release}/publication.json" <<'PYNEWEST'
import json,subprocess,sys
required={a["name"] for a in json.load(open(sys.argv[1]))["assets"]}
required|={n+".sha256" for n in list(required)}
tags=json.loads(subprocess.check_output(["gh","release","list","--limit","50","--json","tagName,isDraft"],text=True))
for release in tags:
    if release["isDraft"] or not release["tagName"].startswith("v"):
        continue
    assets=json.loads(subprocess.check_output(["gh","release","view",release["tagName"],"--json","assets"],text=True))["assets"]
    if required <= {a["name"] for a in assets}:
        print(release["tagName"]); break
else:
    sys.exit(1)
PYNEWEST
}

if [[ "$channel" == "tip" ]]; then
    channel_prefix="$s3_prefix/tip"
    feed_url="$public_base/tip/appcast.xml"
    tag="tip"
    git fetch -q origin
    latest_release="$(git describe --tags --abbrev=0 --match 'v[0-9]*' origin/main 2>/dev/null)" \
        || fail "no release tag on origin/main to version the tip after"
    if [[ "$mode" == "--publish-only" ]]; then
        # The prepared build is pinned by dist/release.json; main may have
        # moved on since, which doesn't matter for publishing it.
        version="$(python3 -c 'import json; print(json.load(open("dist/release.json"))["version"])')"
        [[ "$version" == *-tip.* ]] || fail "dist/ holds no prepared tip build"
        build_number="$(python3 -c 'import json; print(json.load(open("dist/release.json"))["build"])')"
    else
        # Tips are main plus more: never one that lacks something on main.
        git merge-base --is-ancestor origin/main HEAD \
            || fail "this branch doesn't contain the latest origin/main; merge or rebase it onto main first"
        base="${latest_release#v}"
        # <release build>.<n>: n counts up past the live tip of the same
        # release, whatever branch it came from, so Sparkle offers the newest.
        release_build="$(git rev-list --count "$latest_release")"
        previous="$(live_tip_build)"
        sequence=1
        if [[ "$previous" == "$release_build".* ]]; then sequence=$(( ${previous#*.} + 1 )); fi
        build_number="$release_build.$sequence"
        version="${base%.*}.$(( ${base##*.} + 1 ))-tip.$sequence"
    fi
    # Tips reuse the newest published Windows runtime; they never publish one.
    [[ -z "${REUSE_WINDOWS_ASSETS_FROM+set}" || -n "$REUSE_WINDOWS_ASSETS_FROM" ]] \
        || fail "tips reuse a published Windows runtime; leave REUSE_WINDOWS_ASSETS_FROM unset or name a release"
    if [[ -z "${REUSE_WINDOWS_ASSETS_FROM:-}" ]]; then
        REUSE_WINDOWS_ASSETS_FROM="$(newest_release_with_windows_runtime)" \
            || fail "no published release carries this Windows runtime"
    fi
    step "Tip $version from $(git rev-parse --abbrev-ref HEAD) @ $(git rev-parse --short HEAD)"
fi
download_base="$s3_endpoint/$s3_bucket/$channel_prefix"

# The tip: a link that always gets the newest, the moving "tip" tag and
# pre-release, then the feed, which is what tip copies update from.
publish_tip() {
    local latest="$dist/Waypoint-Tip.dmg" branch notes live
    [[ "$channel_prefix" == "$s3_prefix/tip" ]] || fail "tip publishing outside the tip prefix"
    # Another tip may have gone out since this one was built.
    live="$(live_tip_build)"
    [[ -z "$live" ]] || python3 -c 'import sys; a,b=(tuple(map(int,v.split("."))) for v in sys.argv[1:]); sys.exit(a<=b)' "$build_number" "$live" \
        || fail "the live tip ($live) is as new as this one ($build_number); build again"
    cp "$dmg" "$latest"
    (cd "$dist" && shasum -a 256 "${latest:t}" >"${latest:t}.sha256")
    s3 cp "$latest" "s3://$s3_bucket/$channel_prefix/${latest:t}" --content-type application/x-apple-diskimage --cache-control no-cache
    branch="$(git rev-parse --abbrev-ref HEAD)"
    git tag -f -a tip -m "Waypoint $version" >/dev/null
    git push -f -q origin refs/tags/tip
    notes="$(mktemp)"
    {
        print "**Tip build: Waypoint $version**, from \`$branch\` at $(git rev-parse --short HEAD), on top of the latest \`main\`."
        print
        print "Tip builds carry experimental work that hasn't been released. They update to the next tip, or the next release, on their own. To go back to releases, turn off **Get tip builds** in Settings ▸ General, or install the [latest release]($repo_url/releases/latest) over it."
        print
        print "Download: [Waypoint-Tip.dmg]($download_base/${latest:t}) · $(awk '{print $1}' "$latest.sha256")"
        [[ -z "${NOTES_FILE:-}" ]] || { print; cat "$NOTES_FILE" }
    } >"$notes"
    if gh release view tip >/dev/null 2>&1; then
        gh release edit tip --prerelease --latest=false --title "Waypoint Tip" --notes-file "$notes"
        gh release upload tip "$latest" "$latest.sha256" --clobber
    else
        gh release create tip "$latest" "$latest.sha256" --prerelease --latest=false --title "Waypoint Tip" --notes-file "$notes" --verify-tag
    fi
    rm -f "$notes"
    # The newest release goes in too: whichever is newer is offered.
    curl -fsS "$public_base/appcast.xml" -o "$dist/release-appcast.xml" || fail "can't read the release feed"
    python3 scripts/merge-tip-appcast.py "$dist/appcast.xml" "$dist/release-appcast.xml" "$dist/tip-appcast.xml"
    s3 cp "$dist/tip-appcast.xml" "s3://$s3_bucket/$channel_prefix/appcast.xml" --content-type application/xml --cache-control no-cache
    curl -fs "$feed_url" | cmp -s - "$dist/tip-appcast.xml" || fail "the public feed at $feed_url doesn't match the new appcast"
    print -P "%F{green}Live tip:%f $feed_url"
}

# After a release: the tip feed offers it too, so tip copies get it.
add_release_to_tip_feed() {
    local tip_feed="$public_base/tip/appcast.xml" code
    code="$(curl -sS --max-time 30 -o "$dist/live-tip-appcast.xml" -w '%{http_code}' "$tip_feed")" || fail "can't read $tip_feed"
    case "$code" in
        403|404) return 0 ;;   # no tips yet
        200) ;;
        *) fail "$tip_feed answered HTTP $code" ;;
    esac
    python3 scripts/merge-tip-appcast.py "$dist/live-tip-appcast.xml" "$dist/appcast.xml" "$dist/tip-appcast.xml"
    s3 cp "$dist/tip-appcast.xml" "s3://$s3_bucket/$s3_prefix/tip/appcast.xml" --content-type application/xml --cache-control no-cache
    curl -fs "$tip_feed" | cmp -s - "$dist/tip-appcast.xml" || fail "the tip feed at $tip_feed doesn't match"
    print -P "%F{green}Tip feed offers it too:%f $tip_feed"
}

# After a release: point the Homebrew cask (brew install --cask
# wowlocal/tap/waypoint) at it. Only the latest release, so a rerun for an
# older tag can't move brew back. The checksum is GitHub's own digest of the
# DMG asset, the file brew downloads.
update_homebrew_cask() {
    local cask_repo="wowlocal/homebrew-tap" cask_path="Casks/waypoint.rb" sha blob current updated
    [[ "$(gh release view --json tagName --jq .tagName 2>/dev/null)" == "$tag" ]] \
        || fail "$tag isn't the latest published GitHub release"
    sha="$(gh release view "$tag" --json assets --jq ".assets[] | select(.name == \"Waypoint-$version.dmg\") | .digest")"
    sha="${sha#sha256:}"
    [[ "$sha" =~ ^[0-9a-f]{64}$ ]] || fail "can't read the checksum of $tag's DMG from GitHub"
    [[ ! -f "$dist/Waypoint-$version.dmg.sha256" || "$(awk '{print $1}' "$dist/Waypoint-$version.dmg.sha256")" == "$sha" ]] \
        || fail "GitHub's checksum for $tag differs from dist/Waypoint-$version.dmg.sha256"
    blob="$(gh api "repos/$cask_repo/contents/$cask_path" --jq .sha)" || fail "can't read $cask_repo/$cask_path"
    current="$(gh api "repos/$cask_repo/contents/$cask_path" -H 'Accept: application/vnd.github.raw')" \
        || fail "can't read $cask_repo/$cask_path"
    updated="$(print -r -- "$current" | sed -E "s/^(  version )\"[^\"]*\"/\1\"$version\"/; s/^(  sha256 )\"[0-9a-f]{64}\"/\1\"$sha\"/")"
    [[ "$updated" == *$'\n  version "'"$version"$'"\n'* && "$updated" == *$'\n  sha256 "'"$sha"$'"\n'* ]] \
        || fail "$cask_path doesn't have the expected version and sha256 lines"
    if [[ "$updated" != "$current" ]]; then
        gh api -X PUT "repos/$cask_repo/contents/$cask_path" -f message="Update Waypoint to $version" \
            -f content="$(print -r -- "$updated" | base64)" -f sha="$blob" >/dev/null \
            || fail "can't update $cask_repo/$cask_path"
    fi
    print -P "%F{green}Homebrew cask:%f $version"
}

if [[ -f scripts/release.env ]]; then
    set -a
    source scripts/release.env
    set +a
fi
[[ "${WINDOWS_EXPERIMENTAL:-0}" != "1" ]] || fail "experimental Windows profiles cannot use the public release pipeline"
sparkle_bin=".build/artifacts/sparkle/Sparkle/bin"
profile="${NOTARY_KEYCHAIN_PROFILE:-${NOTARY_PROFILE:-keys-cli-notary}}"
# Separate from build/Waypoint.app, which may be running.
app="build/release/Waypoint.app"
dist="dist"
if (( tip_feed_only )); then
    [[ -f "$dist/appcast.xml" ]] && grep -q "<sparkle:shortVersionString>$version<" "$dist/appcast.xml" \
        || fail "dist/appcast.xml isn't $version's; publish the release first"
    command -v aws >/dev/null || fail "aws CLI not found (brew install awscli)"
    add_release_to_tip_feed
    exit 0
fi
if (( homebrew_only )); then
    update_homebrew_cask
    exit 0
fi
dmg="$dist/Waypoint-$version.dmg"
component="${WINDOWS_COMPONENT_RELEASE:-build/windows-runtime-release}"
export WINDOWS_RUNTIME="$component/distribution"
reuse_windows_from="${REUSE_WINDOWS_ASSETS_FROM:-}"
if [[ -z "$reuse_windows_from" ]]; then
    python3 scripts/validate-windows-publication.py "$component"
else
    # Check only the small release metadata: the content-addressed archives
    # must already be public. Do not download or hash them again.
    published_assets="$(mktemp)"
    gh release view "$reuse_windows_from" --json isDraft,assets >"$published_assets"
    python3 - "$component/publication.json" "$published_assets" <<'PYREUSE'
import json,pathlib,sys
component=json.loads(pathlib.Path(sys.argv[1]).read_text())
release=json.loads(pathlib.Path(sys.argv[2]).read_text())
if release["isDraft"]:
    raise SystemExit("Cannot reuse Windows assets from a draft release")
published={a["name"] for a in release["assets"]}
required={a["name"] for a in component["assets"]}
required|={name+".sha256" for name in required.copy()}
if not required <= published:
    raise SystemExit("The selected release does not contain these Windows assets")
PYREUSE
    rm -f "$published_assets"
    step "Reusing Windows assets from $reuse_windows_from"
fi

# Preconditions first, so a missing credential doesn't cost a full build.
[[ -z "$(git status --porcelain)" || -n "${ALLOW_DIRTY:-}" ]] \
    || fail "working tree has uncommitted changes (ALLOW_DIRTY=1 to build anyway)"
identity="${SIGN_IDENTITY:-$(security find-identity -v -p codesigning | sed -n 's/.*"\(Developer ID Application:.*\)"/\1/p' | awk 'NR == 1')}"
[[ -n "$identity" ]] || fail "no Developer ID Application identity in the keychain"
if [[ -n "${NOTARY_KEY:-}" ]]; then
    [[ -n "${NOTARY_KEY_ID:-}" ]] || fail "NOTARY_KEY also needs NOTARY_KEY_ID"
    notary_auth=(--key "$NOTARY_KEY" --key-id "$NOTARY_KEY_ID")
    [[ -z "${NOTARY_ISSUER:-}" ]] || notary_auth+=(--issuer "$NOTARY_ISSUER")
    xcrun notarytool history "${notary_auth[@]}" >/dev/null 2>&1 || fail "Apple rejected the App Store Connect API key"
else
    notary_auth=(-p "$profile")
    xcrun notarytool history "${notary_auth[@]}" >/dev/null || fail "notarytool could not access profile \"$profile\". Inspect the error above and keychain/network access."
fi
# Sparkle tools come with the package; resolve it if this is a fresh checkout.
[[ -x "$sparkle_bin/generate_appcast" ]] || xcrun swift package resolve
private_key_public_half="$("$sparkle_bin/generate_keys" --account waypoint -p 2>/dev/null || true)"
[[ -n "$private_key_public_half" ]] || fail "no Sparkle signing key in the keychain (account \"waypoint\")"
[[ "$(<scripts/bundle.sh)" == *"sparkle_public_key=\"$private_key_public_half\""* ]] \
    || fail "the keychain's Sparkle key doesn't match the public key in scripts/bundle.sh; updates would be rejected"
if (( publish )) && [[ "$channel" == "tip" ]]; then
    gh auth status >/dev/null 2>&1 || fail "gh is not logged in"
    command -v aws >/dev/null || fail "aws CLI not found (brew install awscli)"
    s3 ls "s3://$s3_bucket/" >/dev/null || fail "can't reach s3://$s3_bucket/; check the S3 credentials"
elif (( publish )); then
    if git rev-parse -q --verify "refs/tags/$tag" >/dev/null; then
        [[ "$(git rev-list -n 1 "$tag")" == "$(git rev-parse HEAD)" ]] || fail "tag $tag points to another commit"
        [[ "$mode" == "--publish-only" ]] || fail "tag already exists; resume the exact artifacts with --publish-only"
    fi
    git fetch -q origin
    git merge-base --is-ancestor HEAD origin/main || fail "HEAD is not on origin/main; push it first"
    gh auth status >/dev/null 2>&1 || fail "gh is not logged in"
    [[ "$(gh release view "$tag" --json isDraft --jq .isDraft 2>/dev/null || true)" != "false" ]] \
        || fail "release $tag is already public"
    command -v aws >/dev/null || fail "aws CLI not found (brew install awscli)"
    # List the bucket, not the prefix: `aws s3 ls` exits 1 on an empty prefix (the first release).
    s3 ls "s3://$s3_bucket/" >/dev/null || fail "can't reach s3://$s3_bucket/; check the S3 credentials"
fi

if [[ "$mode" != "--publish-only" ]]; then
step "Testing"
xcrun swift test

step "Building Waypoint $version"
APP_PATH="$app" VERSION="$version" SIGN_IDENTITY="$identity" SPARKLE_FEED="$feed_url" CHANNEL="$channel" \
    BUILD_NUMBER="${build_number:-$(git rev-list --count HEAD)}" scripts/bundle.sh
codesign --verify --deep --strict "$app"
[[ -n "$reuse_windows_from" ]] || python3 scripts/validate-windows-publication.py "$component" --app "$app"
[[ "$(/usr/libexec/PlistBuddy -c 'Print SUFeedURL' "$app/Contents/Info.plist")" == "$feed_url" ]] \
    || fail "the app's SUFeedURL doesn't match $feed_url"
# Capture first: `grep -q` exits early and pipefail would count codesign's SIGPIPE as failure.
signature="$(codesign -dvv "$app" 2>&1)"
[[ "$signature" == *"(runtime)"* ]] || fail "hardened runtime is not enabled"

# notarize <file>: submit, wait, and on rejection print Apple's log.
notarize() {
    local file="$1" result
    result="$(mktemp)"
    step "Notarizing ${file:t} (usually a few minutes)"
    xcrun notarytool submit "$file" "${notary_auth[@]}" --wait --timeout 1h --output-format json >"$result" || true
    local notary_status id
    notary_status="$(plutil -extract status raw -o - "$result" 2>/dev/null || echo unknown)"
    if [[ "$notary_status" != "Accepted" ]]; then
        cat "$result" >&2
        id="$(plutil -extract id raw -o - "$result" 2>/dev/null || true)"
        [[ -n "$id" ]] && xcrun notarytool log "$id" "${notary_auth[@]}" >&2
        fail "notarization of ${file:t}: $notary_status"
    fi
    rm -f "$result"
}

rm -rf "$dist"
mkdir -p "$dist"

# The app first, so it carries its own ticket even outside the DMG.
zip="$dist/Waypoint-$version-app.zip"
ditto -c -k --keepParent "$app" "$zip"
notarize "$zip"
rm -f "$zip"
xcrun stapler staple "$app"

step "Packaging $dmg"
staging="$(mktemp -d)"
mount="$(mktemp -d)"
trap 'rm -rf "$staging"; hdiutil detach -quiet "$mount" 2>/dev/null || true; rmdir "$mount" 2>/dev/null || true' EXIT
ditto "$app" "$staging/Waypoint.app"
ln -s /Applications "$staging/Applications"
hdiutil create -quiet -volname "Waypoint $version" -srcfolder "$staging" -fs HFS+ -format UDZO -ov "$dmg"
codesign --force --sign "$identity" --timestamp "$dmg"
notarize "$dmg"
xcrun stapler staple "$dmg"

step "Verifying"
xcrun stapler validate "$dmg"
spctl --assess --type open --context context:primary-signature --verbose "$dmg"
hdiutil attach -quiet -nobrowse -readonly -mountpoint "$mount" "$dmg"
spctl --assess --type execute --verbose "$mount/Waypoint.app"
xcrun stapler validate "$mount/Waypoint.app"
hdiutil detach -quiet "$mount"
(cd "$dist" && shasum -a 256 "${dmg:t}" >"${dmg:t}.sha256")

step "Generating appcast"
feed_dir="$(mktemp -d)"
cp "$dmg" "$feed_dir/"
# One item per release and no deltas. The Windows runtime is separate and reused.
"$sparkle_bin/generate_appcast" --account waypoint --maximum-deltas 0 \
    --download-url-prefix "$download_base/" --link "$repo_url" \
    -o "$dist/appcast.xml" "$feed_dir"
rm -rf "$feed_dir"
signature="$(sed -n 's/.*sparkle:edSignature="\([^"]*\)".*/\1/p' "$dist/appcast.xml" | awk 'NR == 1')"
[[ -n "$signature" ]] || fail "appcast has no EdDSA signature"
"$sparkle_bin/sign_update" --account waypoint --verify "$dmg" "$signature" || fail "appcast signature doesn't match the DMG"
grep -q "url=\"$download_base/${dmg:t}\"" "$dist/appcast.xml" || fail "appcast points somewhere unexpected"
print -P "%F{green}Ready:%f $dmg"
python3 - "$version" "$app" "$dmg" "$dist/appcast.xml" "$component/publication.json" <<'PY'
import hashlib,json,pathlib,subprocess,sys
version,*names=sys.argv[1:]
import plistlib
build=plistlib.load(open(names.pop(0)+"/Contents/Info.plist","rb"))["CFBundleVersion"]
d={"version":version,"build":build,"commit":subprocess.check_output(["git","rev-parse","HEAD"],text=True).strip(),
   "files":{name:hashlib.sha256(pathlib.Path(name).read_bytes()).hexdigest() for name in names}}
pathlib.Path("dist/release.json").write_text(json.dumps(d,indent=2)+"\n")
PY
fi

if (( publish )); then
    python3 - "$version" <<'PY'
import hashlib,json,pathlib,subprocess,sys
d=json.loads(pathlib.Path("dist/release.json").read_text())
if d["version"]!=sys.argv[1] or d["commit"]!=subprocess.check_output(["git","rev-parse","HEAD"],text=True).strip():
    raise SystemExit("Prepared release does not match this version/commit")
for name,expected in d["files"].items():
    if hashlib.sha256(pathlib.Path(name).read_bytes()).hexdigest()!=expected:
        raise SystemExit("Prepared artifact changed: "+name)
PY
    [[ -n "$reuse_windows_from" ]] || python3 scripts/validate-windows-publication.py "$component" --app "$app"
    step "Publishing $tag"
    # Upload corresponding sources and runtime before any app refers to them.
    # Required-only checksums are compatible with the S3 provider's multipart API.
    export AWS_REQUEST_CHECKSUM_CALCULATION=when_required
    assets=()
    if [[ -z "$reuse_windows_from" ]]; then
    while IFS=$'\t' read -r name key bytes asset_sha; do
        http_status="$(curl -sS -o /dev/null -w '%{http_code}' -I "$public_base/$key")"
        case "$http_status" in
            200) ;; # Never replace a component object already served to users.
            404) s3 cp "$component/$name" "s3://$s3_bucket/$s3_prefix/$key" --only-show-errors --metadata "sha256=$asset_sha" </dev/null ;;
            *) fail "can't check immutable component asset: HTTP $http_status ($name)" ;;
        esac
        [[ "$(curl -fsS "$public_base/$key" | shasum -a 256 | awk '{print $1}')" == "$asset_sha" ]] \
            || fail "published component asset differs; refusing to replace it: $name"
        [[ "$(curl -fsI "$public_base/$key" | awk 'tolower($1) == "content-length:" { print $2 + 0 }')" == "$bytes" ]] \
            || fail "component asset isn't publicly served at the right size: $name"
        assets+=("$component/$name" "$component/$name.sha256")
    done < <(python3 - "$component/publication.json" <<'PY'
import json,sys
for a in json.load(open(sys.argv[1]))["assets"]:
    print(a["name"],a["key"],a["bytes"],a["sha256"],sep="\t")
PY
    )
    (( ${#assets} == 4 )) || fail "not every component asset was published"
    fi
    step "Uploading to s3://$s3_bucket/$channel_prefix/"
    s3 cp "$dmg" "s3://$s3_bucket/$channel_prefix/${dmg:t}" --content-type application/x-apple-diskimage
    [[ "$(curl -fsI "$download_base/${dmg:t}" | awk 'tolower($1) == "content-length:" { print $2 + 0 }')" == "$(stat -f %z "$dmg")" ]] \
        || fail "$download_base/${dmg:t} isn't publicly served at the right size"
    if [[ "$channel" == "tip" ]]; then
        publish_tip
        exit 0
    fi
    if ! git rev-parse -q --verify "refs/tags/$tag" >/dev/null; then git tag -a "$tag" -m "Waypoint $version"; fi
    git push origin "$tag"
    step "Staging GitHub release"
    notes=(--generate-notes)
    [[ -n "${NOTES_FILE:-}" ]] && notes=(--notes-file "$NOTES_FILE")
    if gh release view "$tag" --json isDraft --jq .isDraft 2>/dev/null | grep -q true; then
        gh release upload "$tag" "$dmg" "$dmg.sha256" "${assets[@]}" --clobber
    else
        gh release create "$tag" "$dmg" "$dmg.sha256" "${assets[@]}" --draft --title "Waypoint $version" --verify-tag "${notes[@]}"
    fi
    # The feed is the first step that activates automatic distribution.
    s3 cp "$dist/appcast.xml" "s3://$s3_bucket/$s3_prefix/appcast.xml" --content-type application/xml --cache-control no-cache
    curl -fs "$feed_url" | cmp -s - "$dist/appcast.xml" || fail "the public feed at $feed_url doesn't match the new appcast"
    gh release edit "$tag" --draft=false --latest
    print -P "%F{green}Live:%f $feed_url"
    # Subshells, so a failure in one (fail exits) still runs the other and
    # ends with the commands that finish the job.
    followups=()
    ( add_release_to_tip_feed ) || followups+=("scripts/release.sh $version --tip-feed")
    ( update_homebrew_cask ) || followups+=("scripts/release.sh $version --homebrew")
    (( ${#followups} == 0 )) || fail "the release is live, but not everywhere yet; run: ${(j: and :)followups}"
fi
